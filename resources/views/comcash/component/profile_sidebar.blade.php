<script>
    const $ = (selector) => document.querySelector(selector);
    const $$ = (selector) => Array.from(document.querySelectorAll(selector));

    const overlay = $('#menuOverlay2');
    const tabButtons = $$('.tab-btn');
    const backButtons = $$('.back-to-main-tabs');

    const defaultTabs = $('#default-tabs');
    const partnerTabs = $('#partner-tabs');
    const partnersSubmenu = $('#partners-submenu');
    const arrowIcon = $('#arrow-icon');

    const isMobile = () => window.innerWidth <= 400;

    const openOverlay = () => {
        if (!overlay) return;
        overlay.classList.remove('opacity-0', 'pointer-events-none');
        overlay.classList.add('opacity-100', 'pointer-events-auto');
        document.documentElement.classList.add('overflow-hidden');
    };

    const closeOverlay = () => {
        if (!overlay) return;
        overlay.classList.remove('opacity-100', 'pointer-events-auto');
        overlay.classList.add('opacity-0', 'pointer-events-none');
        document.documentElement.classList.remove('overflow-hidden');
    };

    const evaluateOverlayVisibility = () => {
        isMobile() ? openOverlay() : closeOverlay();
    };

    const handleTabClick = (btn) => {
        const wasActive = btn.dataset.active === 'true';

        tabButtons.forEach((b) => b.dataset.active = 'false');
        btn.dataset.active = wasActive ? 'false' : 'true';

        if (isMobile()) closeOverlay();
    };

    const handleBackToMainTabs = () => {
        partnerTabs?.classList.add('hidden');
        defaultTabs?.classList.remove('hidden');
        partnersSubmenu?.classList.add('hidden');
        arrowIcon?.classList.remove('rotate-180');

        if (isMobile()) openOverlay();
    };

    document.addEventListener('DOMContentLoaded', () => {
        tabButtons.forEach((btn) =>
            btn.addEventListener('click', () => handleTabClick(btn))
        );

        backButtons.forEach((btn) =>
            btn.addEventListener('click', handleBackToMainTabs)
        );

        evaluateOverlayVisibility();
    });

    window.addEventListener('resize', evaluateOverlayVisibility);
</script>
@endsection
